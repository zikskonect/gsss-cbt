function getDataDir() {
    const home = os.homedir();
    return process.platform==='win32' ? path.join(process.env.APPDATA,'GSS-CBT') : path.join(home,'.gss-cbt');
}

async function backupDatabase() {
    const runtime = getRuntimeDir();
    const dataDir = path.join(runtime, 'mariadb', 'data');
    const backupsDir = path.join(getDataDir(), 'backups');
    if (!fs.existsSync(backupsDir)) fs.mkdirSync(backupsDir,{recursive:true});
    const stamp = new Date().toISOString().replace(/[:.]/g,'-').slice(0,19);
    const outFile = path.join(backupsDir, `backup_${stamp}.sql`);
    
    // Try mysqldump if available
    const dumpBin = path.join(runtime, 'mariadb','bin', process.platform==='win32' ? 'mysqldump.exe' : 'mysqldump');
    if (fs.existsSync(dumpBin)) {
        try {
            execSync(`"${dumpBin}" --port=3307 -u root cbt_platform > "${outFile}"`, {timeout:10000});
        } catch(e) {
            fs.writeFileSync(outFile, `-- Backup fallback - copy data folder manually\n-- Data dir: ${dataDir}`);
        }
    } else {
        // Just copy data dir as backup marker
        fs.writeFileSync(outFile, `-- Manual backup needed - copy ${dataDir} to safe location`);
    }
    return { path: outFile };
}

module.exports = { ensureRuntime, ensureConfigFile, backupDatabase, getDataDir };