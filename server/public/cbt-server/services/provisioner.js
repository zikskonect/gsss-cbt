const fs = require('fs');
const path = require('path');
const os = require('os');
const { execSync } = require('child_process');

function getRuntimeDir() {
    const devPath = path.join(__dirname, '..', 'runtime');
    return fs.existsSync(path.join(devPath,'webroot')) ? devPath : path.join(__dirname, '..', 'runtime');
}

async function ensureRuntime(logCb) {
    const runtime = getRuntimeDir();
    const webroot = path.join(runtime, 'webroot');
    const phpDir = path.join(runtime, 'php');
    const mariaDir = path.join(runtime, 'mariadb');
    
    if (!fs.existsSync(webroot)) {
        fs.mkdirSync(webroot,{recursive:true});
        logCb('Created runtime/webroot - COPY your server/public files here');
    }
    // Check for PHP
    const phpBin = path.join(phpDir, process.platform==='win32' ? 'php.exe' : 'bin/php');
    if (!fs.existsSync(phpBin)) {
        logCb('⚠️ Portable PHP not found. Download from https://windows.php.net/downloads/releases/ - extract php-8.2-nts-Win32-vs16-x64.zip to runtime/php/');
    }
    // Check MariaDB
    const mariaBin = path.join(mariaDir, 'bin', process.platform==='win32' ? 'mysqld.exe' : 'mariadbd');
    if (!fs.existsSync(mariaBin)) {
        logCb('⚠️ Portable MariaDB not found. Download from https://downloads.mariadb.org/ - extract to runtime/mariadb/');
    }
    return { webroot, phpDir, mariaDir };
}

